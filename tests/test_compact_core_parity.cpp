// Compare the miner's compact decoder against the PINNED PEPEPOW Core's
// arith_uint256::SetCompact, linked from its original source (not a rewrite).
// This checks only raw target decoding and sign/overflow flags. Network
// powLimit, activation time and CheckProofOfWork remain separate concerns.
#include "arith_uint256.h"
#include "uint256.h"
#include "pepepow/compact_target.h"

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <cstdint>

static unsigned long long checked = 0;

static void check(uint32_t bits) {
    bool negative = false, overflow = false;
    arith_uint256 reference;
    reference.SetCompact(bits, &negative, &overflow);
    const bool valid = !negative && !overflow && reference != 0;

    uint8_t actual[32];
    std::memset(actual, 0xa5, sizeof(actual));
    const int accepted = pepepow_decode_compact(bits, actual);
    if (accepted != static_cast<int>(valid)) {
        std::fprintf(stderr, "Core compact validity mismatch: %08x, Core neg=%d overflow=%d zero=%d, miner=%d\n",
                     static_cast<unsigned>(bits), negative, overflow, reference == 0, accepted);
        std::exit(EXIT_FAILURE);
    }
    uint8_t expected[32] = {};
    if (valid) {
        const uint256 raw = ArithToUint256(reference);
        std::memcpy(expected, raw.begin(), sizeof(expected));
    }
    if (std::memcmp(actual, expected, sizeof(expected)) != 0) {
        std::fprintf(stderr, "Core compact full 32-byte target mismatch: %08x\n",
                     static_cast<unsigned>(bits));
        std::exit(EXIT_FAILURE);
    }
    ++checked;
}

int main() {
    // All exponent bytes, every compact-boundary mantissa and both sign bits.
    const uint32_t words[] = {
        0u, 1u, 0x7fu, 0xffu, 0x100u, 0x101u, 0x7fffu,
        0xffffu, 0x10000u, 0x10001u, 0x7effffu, 0x7ffffeu, 0x7fffffu
    };
    for (uint32_t exponent = 0; exponent != 256u; ++exponent) {
        for (uint32_t word : words) {
            for (uint32_t sign = 0; sign <= 1u; ++sign) {
                check((exponent << 24) | word | (sign << 23));
            }
        }
    }

    // Repeatable deterministic 32-bit inputs, not generated by the miner.
    uint32_t state = 0x85ebca6bu;
    for (unsigned i = 0; i < 100000u; ++i) {
        state ^= state << 13;
        state ^= state >> 17;
        state ^= state << 5;
        check(state);
    }

    // Frequently encountered textbook examples; not asserted to be chain data.
    const uint32_t examples[] = {
        0x1d00ffffu, 0x1e0fffffu, 0x1f00ffffu, 0x207fffffu,
        0x0101ffffu, 0x0201ffffu, 0x220000ffu, 0x23000001u
    };
    for (uint32_t bits : examples) check(bits);
    std::printf("pinned Core SetCompact parity: %llu complete 32-byte targets PASS\n", checked);
    return EXIT_SUCCESS;
}
